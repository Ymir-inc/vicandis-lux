/**
 * Regenerates the whole icon set from one vector source.
 *
 *   npm run icons
 *
 * The artwork below is a hand-traced simplification of
 * `public/brand/vicandislux-mark.webp` — the gold "VL" the header renders.
 * Everything the browser, Android, iOS and Google's favicon crawler ask for is
 * a render of this single drawing, so the tab icon, the PWA icon and the
 * search-result icon can never drift apart again.
 *
 * Deliberate departures from the source mark, all in service of 16px legibility:
 *   - the enclosing gold ring is dropped; the dark tile becomes the container
 *     (a hairline ring plus a tile outline is two competing silhouettes, and at
 *     16px the ring is a sub-pixel smear that only greys out the letters);
 *   - the four interleaved wave ribbons collapse to one tapered swash;
 *   - the letters are drawn heavier than the source's Trajan-like face, whose
 *     hairline serifs disappear below ~32px.
 * The "VL" ligature — one shared serif bar spanning the V's right arm and the
 * L's stem, V in gold, L in cream — is preserved exactly.
 *
 * The dark tile is not optional: the mark is gold-on-transparent in the source,
 * which vanishes against a light browser tab strip.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { CREAM, CREAM_DEEP, GOLD, GOLD_DEEP, GOLD_LIGHT, TILE } from './brand.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Corner radius in the 512 design space (~22%, matching platform app tiles). */
const RADIUS = 112;

/*
  Design space is 512x512. Cap height runs 130 → 360 with the V's apex
  overshooting to 366, as a pointed terminal must to sit optically on the
  baseline. Serif depth is 26 (≈1.6px at 32px) — the thinnest that survives
  favicon downsampling.
*/
const V = 'M96 130h102v26h-20l40 100 40-100h-18v-26h62v26h-18l-84 210-84-210H96z';
const L = 'M302 130h86v26h-16v160h44l12-12v58H320V156h-18z';
const WAVE = 'M72 392c78 46 290 46 368 0-78 106-290 106-368 0z';

/** Metallic sheen shared by the V and the swash, lit from the top-left. */
const DEFS = `<linearGradient id="au" gradientUnits="userSpaceOnUse" x1="96" y1="80" x2="420" y2="400">
      <stop offset="0" stop-color="${GOLD_LIGHT}"/>
      <stop offset=".42" stop-color="${GOLD}"/>
      <stop offset="1" stop-color="${GOLD_DEEP}"/>
    </linearGradient>
    <linearGradient id="cr" gradientUnits="userSpaceOnUse" x1="300" y1="90" x2="430" y2="330">
      <stop offset="0" stop-color="${CREAM}"/>
      <stop offset="1" stop-color="${CREAM_DEEP}"/>
    </linearGradient>`;

/** Centres the drawing: the letters sit 6 right of centre, the whole 45 low. */
const ART = `<g transform="translate(-6,-45)">
      <path d="${V}" fill="url(#au)"/>
      <path d="${L}" fill="url(#cr)"/>
    </g>
    <g transform="translate(0,-45)"><path d="${WAVE}" fill="url(#au)"/></g>`;

/**
 * @param {object} o
 * @param {number} [o.rx]    corner radius; 0 for full-bleed (maskable, iOS)
 * @param {number} [o.scale] uniform scale about the tile centre
 * @param {number} [o.size]  declared width/height. librsvg rasterises to the
 *   declared size, not to the viewBox, so this has to be the target size: a
 *   32px render blown up to 512 is a blurry mess. It is an argument rather
 *   than a `String.replace` on the finished markup because a replace that
 *   stops matching — reordered attributes, a changed default, an extra space
 *   — returns the input untouched and throws nothing, which is precisely the
 *   blurry output this exists to prevent, delivered silently.
 */
function tile({ rx = RADIUS, scale = 1.04, size = 32 } = {}) {
  return `<!-- Generated by scripts/generate-icons.mjs; rebuild with \`npm run icons\`. Edits here are overwritten. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 512 512" role="img" aria-label="VicandisLux">
  <defs>
    ${DEFS}
  </defs>
  <rect width="512" height="512" rx="${rx}" fill="${TILE}"/>
  <g transform="translate(256,256) scale(${scale}) translate(-256,-256)">
    ${ART}
  </g>
</svg>
`;
}

/**
 * The three tiles, held as arguments rather than as finished markup: each is
 * rasterised at several sizes, and `tile()` needs the size up front.
 */
const ROUNDED = {};
/* Maskable: Android crops to a circle of 80% diameter, so the drawing has to
   fit inside r=204.8 while the dark tile bleeds to all four edges. At the
   default 1.04 the art's half-diagonal is ~248; 0.85 brings it to ~203. */
const MASKABLE = { rx: 0, scale: 0.85 };
/* iOS applies its own squircle and composites on white, so: square and opaque. */
const APPLE = { rx: 0 };

const raster = (variant, size) => sharp(Buffer.from(tile({ ...variant, size })));

const render = (variant, size, { opaque = false } = {}) => {
  const img = raster(variant, size);
  return (opaque ? img.flatten({ background: TILE }).removeAlpha() : img)
    .png({ compressionLevel: 9 })
    .toBuffer();
};

/**
 * Packs PNG-free, 32-bit BGRA DIB entries into a multi-resolution .ico.
 * BMP entries rather than embedded PNGs: the PNG-in-ICO form needs Vista+ and
 * some favicon crawlers and feed readers still choke on it, while every decoder
 * ever written handles a plain DIB.
 */
function ico(images) {
  const dir = Buffer.alloc(6);
  dir.writeUInt16LE(0, 0);
  dir.writeUInt16LE(1, 2); // type: icon
  dir.writeUInt16LE(images.length, 4);

  const entries = [];
  const bodies = [];
  let offset = 6 + images.length * 16;

  for (const { size, data } of images) {
    const maskStride = (((size + 31) >> 5) << 2); // 1bpp rows padded to 4 bytes
    const xor = Buffer.alloc(size * size * 4);
    const and = Buffer.alloc(maskStride * size); // all zero: alpha carries opacity

    for (let y = 0; y < size; y++) {
      const src = y * size * 4;
      const dst = (size - 1 - y) * size * 4; // DIBs are bottom-up
      for (let x = 0; x < size; x++) {
        const s = src + x * 4;
        const d = dst + x * 4;
        xor[d] = data[s + 2]; // B
        xor[d + 1] = data[s + 1]; // G
        xor[d + 2] = data[s]; // R
        xor[d + 3] = data[s + 3]; // A
      }
    }

    const header = Buffer.alloc(40);
    header.writeUInt32LE(40, 0);
    header.writeInt32LE(size, 4);
    header.writeInt32LE(size * 2, 8); // XOR + AND stacked
    header.writeUInt16LE(1, 12);
    header.writeUInt16LE(32, 14);
    header.writeUInt32LE(0, 16); // BI_RGB
    header.writeUInt32LE(xor.length + and.length, 20);

    const body = Buffer.concat([header, xor, and]);
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size === 256 ? 0 : size, 0);
    entry.writeUInt8(size === 256 ? 0 : size, 1);
    entry.writeUInt16LE(1, 4);
    entry.writeUInt16LE(32, 6);
    entry.writeUInt32LE(body.length, 8);
    entry.writeUInt32LE(offset, 12);

    entries.push(entry);
    bodies.push(body);
    offset += body.length;
  }

  return Buffer.concat([dir, ...entries, ...bodies]);
}

const write = async (rel, data) => {
  const abs = join(root, rel);
  await mkdir(dirname(abs), { recursive: true });
  await writeFile(abs, data);
  console.log(`  ${rel}  ${(data.length / 1024).toFixed(1)} KB`);
};

console.log('Generating icons from scripts/generate-icons.mjs');
await write('app/icon.svg', tile(ROUNDED));
await write('public/icons/icon-48.png', await render(ROUNDED, 48));
await write('public/icons/icon-192.png', await render(ROUNDED, 192));
await write('public/icons/icon-512.png', await render(ROUNDED, 512));
await write('public/icons/icon-maskable-512.png', await render(MASKABLE, 512));
await write('app/apple-icon.png', await render(APPLE, 180, { opaque: true }));

const sizes = [16, 32, 48];
const raw = await Promise.all(
  sizes.map(async (size) => ({
    size,
    data: await raster(ROUNDED, size).ensureAlpha().raw().toBuffer(),
  })),
);
await write('public/favicon.ico', ico(raw));
